import opentype from "opentype.js";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const fontPath = path.join(root, "public/assets/fonts/JustAnotherHand-Regular.ttf");
const outPath = path.join(root, "src/lib/field-notes-handwriting-paths.ts");

const VARIANTS = {
  slide: "JB's Field Notes",
  page: "JB's Field Notes #1",
  /** End-of-note sign-off — smiley is drawn separately in the React component. */
  signature: "jb",
};

const FONT_SIZE = 480;
const LETTER_SPACING = 42;
const BASELINE_Y = Math.round(FONT_SIZE * 0.85);
const PADDING_X = 90;
/** Round caps extend past path ends — pad viewBox so strokes are not clipped. */
const STROKE_PAD = 108;

function splitSubpaths(pathData) {
  const parts = pathData
    .split(/(?=M)/)
    .map((segment) => segment.trim())
    .filter(Boolean);
  return parts.length ? parts : [pathData];
}

function loadFont() {
  const buffer = fs.readFileSync(fontPath);
  return opentype.parse(
    buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength),
  );
}

function generatePaths(font, text) {
  let x = PADDING_X;
  const paths = [];
  let strokeOrder = 0;
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;

  for (const char of text) {
    const glyph = font.charToGlyph(char);
    const glyphPath = glyph.getPath(x, BASELINE_Y, FONT_SIZE);
    const bbox = glyphPath.getBoundingBox();
    minX = Math.min(minX, bbox.x1);
    minY = Math.min(minY, bbox.y1);
    maxX = Math.max(maxX, bbox.x2);
    maxY = Math.max(maxY, bbox.y2);

    const pathData = glyphPath.toPathData(2);

    for (const subpath of splitSubpaths(pathData)) {
      paths.push({ d: subpath, strokeOrder });
      strokeOrder += 1;
    }

    x += (glyph.advanceWidth * FONT_SIZE) / font.unitsPerEm + LETTER_SPACING;
  }

  const vbX = Math.floor(minX - STROKE_PAD);
  const vbY = Math.floor(minY - STROKE_PAD);
  const width = Math.ceil(maxX - minX + STROKE_PAD * 2);
  const height = Math.ceil(maxY - minY + STROKE_PAD * 2);

  return {
    text,
    width,
    height,
    viewBox: `${vbX} ${vbY} ${width} ${height}`,
    fontSize: FONT_SIZE,
    letterSpacing: LETTER_SPACING,
    paths,
  };
}

function generate() {
  const font = loadFont();
  const entries = Object.entries(VARIANTS).map(([key, text]) => [
    key,
    generatePaths(font, text),
  ]);

  const file = `/** Generated by \`node scripts/generate-field-notes-handwriting.mjs\` — do not edit by hand. */
${entries
  .map(
    ([key, data]) => `export const FIELD_NOTES_HANDWRITING_${key.toUpperCase()} = ${JSON.stringify(data, null, 2)} as const;`,
  )
  .join("\n\n")}

/** @deprecated Use FIELD_NOTES_HANDWRITING_SLIDE — kept for import stability during refactors. */
export const FIELD_NOTES_HANDWRITING = FIELD_NOTES_HANDWRITING_SLIDE;
`;

  fs.writeFileSync(outPath, file);
  const strokeCount = entries.reduce((sum, [, data]) => sum + data.paths.length, 0);
  console.log(`Wrote ${strokeCount} strokes across ${entries.length} variants to ${outPath}`);
}

generate();
