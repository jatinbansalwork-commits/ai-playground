import opentype from "opentype.js";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const fontPath = path.join(root, "public/assets/fonts/Kalam-Bold.ttf");
const outPath = path.join(root, "src/lib/field-notes-handwriting-paths.ts");

const TEXT = "JB's Field Notes";
const FONT_SIZE = 48;
const LETTER_SPACING = 6;
const BASELINE_Y = 40;
const PADDING_X = 10;

function splitSubpaths(pathData) {
  const parts = pathData
    .split(/(?=M)/)
    .map((segment) => segment.trim())
    .filter(Boolean);
  return parts.length ? parts : [pathData];
}

function loadFont() {
  const buffer = fs.readFileSync(fontPath);
  return opentype.parse(
    buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength),
  );
}

function generate() {
  const font = loadFont();

  let measureX = PADDING_X;
  for (const char of TEXT) {
    const glyph = font.charToGlyph(char);
    measureX +=
      (glyph.advanceWidth * FONT_SIZE) / font.unitsPerEm + LETTER_SPACING;
  }

  const width = Math.ceil(measureX + 20);
  const height = 58;

  let x = PADDING_X;
  const paths = [];
  let strokeOrder = 0;

  for (const char of TEXT) {
    const glyph = font.charToGlyph(char);
    const pathData = glyph.getPath(x, BASELINE_Y, FONT_SIZE).toPathData(2);

    for (const subpath of splitSubpaths(pathData)) {
      paths.push({ d: subpath, strokeOrder });
      strokeOrder += 1;
    }

    x += (glyph.advanceWidth * FONT_SIZE) / font.unitsPerEm + LETTER_SPACING;
  }

  const file = `/** Generated by \`node scripts/generate-field-notes-handwriting.mjs\` — do not edit by hand. */
export const FIELD_NOTES_HANDWRITING = {
  text: ${JSON.stringify(TEXT)},
  width: ${width},
  height: ${height},
  viewBox: "0 0 ${width} ${height}",
  fontSize: ${FONT_SIZE},
  letterSpacing: ${LETTER_SPACING},
  paths: ${JSON.stringify(paths, null, 2)},
} as const;
`;

  fs.writeFileSync(outPath, file);
  console.log(`Wrote ${paths.length} strokes to ${outPath}`);
}

generate();
